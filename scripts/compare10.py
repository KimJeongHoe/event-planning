#!/usr/bin/env python3
"""판 10: 비슷한 도구 분석 표 문서 만들기(docs/비슷한도구_국내.json + 해외.json → docs/비슷한도구_분석.md). 도구당 한 번만 분석(공통 지시 6-1)."""
import json,os,collections,re
B=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows=[]
for f in ("국내","해외"):
    for r in json.load(open(f"{B}/docs/비슷한도구_{f}.json",encoding="utf-8")): r["_구분"]=f;rows.append(r)
seen=set();uniq=[]
for r in rows:
    k=re.sub(r"\s+","",r["이름"]).lower()
    if k in seen: continue
    seen.add(k);uniq.append(r)
ok=[r for r in uniq if "확인 못 함" not in (r.get("확인 방법","")+r.get("그 도구가 하는 것",""))]
c=lambda s:(s or "").replace("|","/").replace("\n"," ")
L=["# 비슷한 행사·판촉 기획 도구 분석 (판 10, 2026-11-04)","",
f"국내·해외 소상공인 행사·판촉 도구 {len(uniq)}개(이 가운데 확인 못 한 {len(uniq)-len(ok)}개는 표 끝에 따로)를 도구당 한 번씩 분석했다. 원자료: docs/비슷한도구_국내.json, docs/비슷한도구_해외.json(주소·확인일·확인 방법·가격). 다시 분석하지 않는다(공통 지시 6-1).","",
"## 요약","",
"- **우리가 못 하는 것(많이 나온 순)**: 손님에게 쿠폰·문자·메시지를 실제로 보내기와 자동 발송 / 결제·포스·주문 연동(계산할 때 쿠폰·적립 자동 처리) / 손님 목록·수신 동의 모으기와 데이터 분석 / 손님에게 직접 보이는 노출 통로(지도·배달앱·메신저·딜 사이트) / 디자인 템플릿·인쇄·경품 공식 규정 문서·온라인 응모 추첨 / 인플루언서 모집·매칭",
"- **우리가 나은 것**: 실제 사례 약 1,600건에 근거한 행사 판정 / 업종별 한국 법 근거와 술 광고 판정(해외 도구의 규정 준수는 미국·캐나다 규정에 그침) / 원가·본전 손님 수 계산 / 생성형 AI가 지어낸 문장 없이 자료에서 고름 / 특정 플랫폼에 묶이지 않음",
"- **다음 판 제안으로 넘긴 것**: 이 문서 끝 「다음 판 제안」 절",""]
for f in ("국내","해외"):
    rs=[r for r in ok if r["_구분"]==f]
    L+=[f"## {f} ({len(rs)}개)","","| 도구 | 운영사·나라 | 종류 | 그 도구가 하는 것 | 우리가 못 하는 것 | 우리가 나은 것 |","|---|---|---|---|---|---|"]
    L+=[f"| {c(r['이름'])} | {c(r.get('운영사'))}·{c(r.get('나라'))} | {c(r.get('종류'))} | {c(r.get('그 도구가 하는 것'))} | {c(r.get('우리가 못 하는 것'))} | {c(r.get('우리가 나은 것'))} |" for r in rs]+[""]
nx=[r for r in uniq if r not in ok]
if nx: L+=["## 확인 못 한 도구","",*[f"- {c(r['이름'])} — {c(r.get('확인 방법'))}" for r in nx],""]
L+=["## 다음 판 제안(우리가 못 하는 것에서)","",
"| 못 하는 것 | 이 도구가 할 일인가 | 제안 |","|---|---|---|",
"| 쿠폰·문자 실제 발송, 자동 발송 | 아니오 — 발송은 문자·메시지 도구의 일(공통 지시 5) | 우리 쪽은 발송용 파일(문안·수신 동의 점검 결과·발송 시간 제한)을 넘기는 형식만 만든다 |",
"| 결제·포스 연동(쿠폰·적립 자동 처리) | 아니오 — QR 오더·포스 쪽 도구의 일 | 쿠폰 발급 목록 CSV를 그쪽이 읽는 형식으로 맞추는 칸 설명서 |",
"| 손님 목록·수신 동의 모으기 | 아니오 — 개인정보를 다루지 않는 것이 이 도구 원칙 | 하지 않음. 동의서 문안만 유지 |",
"| 지도·배달앱·메신저 노출 | 아니오 — 플랫폼 기능 | 채널별 글 초안을 플랫폼 글자 수·금지 표현에 더 맞추기(본업) |",
"| 홍보물 디자인 템플릿·인쇄 | 아니오 — 디자인 메이커의 일 | 디자인 메이커용 CSV 칸을 쿠폰 QR(번호·확인 글자)까지 넓히기 |",
"| 경품 공식 규정 문서 생성 | **예 — 행사 기획 본업** | 경품·추첨 도구에 「경품 행사 안내문(응모 기간·당첨 발표·제세공과금·개인정보 처리)」 문안 만들기 추가 |",
"| 마케팅 달력(연간 행사 계획표) | **예 — 본업(날짜는 캘린더 도구 자료)** | 고른 행사안 여러 개를 달력 위에 놓는 「올해 행사 계획」 보기 |",
"| 행사 결과의 업종 평균 비교 | 보류(판 8 결정 유지) | 내 지난 행사끼리 비교를 먼저 |",
"| 인플루언서 모집·매칭 | 아니오 — 중개 플랫폼의 일 | 체험단 계약 점검표 유지 |"]
open(f"{B}/docs/비슷한도구_분석.md","w",encoding="utf-8").write("\n".join(L))
print("분석",len(uniq),"확인",len(ok),"국내",sum(r['_구분']=='국내' for r in ok),"해외",sum(r['_구분']=='해외' for r in ok))
