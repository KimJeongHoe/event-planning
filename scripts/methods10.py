GATE={"가격 혜택":"혜택형","덤·증정":"혜택형|체험·참여형","재방문 장치":"단골·관계형|혜택형","참여 이벤트":"체험·참여형|온라인형","알리기":"사회공헌형|동네매체형|현장연출형|제휴형"}
R=list(csv.DictReader(open(f"{B}/merged/사례DB.csv",encoding="utf-8-sig")))
def txt(r): return " ".join(r.get(k,"") for k in ("이름","혜택","조건"))  # 설명·연출은 배경 문장이 걸려 뺌
real=[r for r in R if r["실제/응용"]=="실제"]
IND=["요식업","소매","서비스업","학원·교육","미용·뷰티","병의원·약국"]
hit={k:[] for k,*_ in M};none=0
for r in R:
    t=txt(r);got=False
    nm=r.get("이름","");ty=r.get("방식","")
    for k,n,g,rx,d,l in M:
        if re.search(rx,nm,flags=re.I) or (re.search(rx,t,flags=re.I) and re.search(GATE[g],ty)): hit[k].append(r);got=True
    if r in real and not got: none+=1
out={"_설명":"판 10 기본 행사 방식 축(scripts/methods10.py가 만듦). 비중 = 실제 사례(원문 확인) 중 그 방식 낱말이 든 사례 비율. 한 사례가 여러 방식에 들 수 있어 합이 100%를 넘음. 응용 사례는 비중에 넣지 않음. 낱말 규칙이라 오분류가 남음. 큰 묶음 순서 = 묶음 안 방식들의 실제 사례 수(중복 없이) 많은 순, 묶음 안 방식 순서 = 비중 큰 순.",
 "기준":{"실제사례":len(real),"전체":len(R),"어느방식에도안듦":none},"묶음":[],"방식":[]}
for k,n,g,rx,d,l in M:
    rr=[r for r in hit[k] if r["실제/응용"]=="실제"]
    by={i:sum(1 for r in rr if i in r["업종"].split("|")) for i in IND}
    tot={i:sum(1 for r in real if i in r["업종"].split("|")) for i in IND}
    out["방식"].append({"키":k,"이름":n,"묶음":g,"설명":d,"법":l,"규칙":rx,"실제":len(rr),"비중":round(len(rr)/len(real)*100,1),
      "업종별":{i:{"건":by[i],"비중":round(by[i]/tot[i]*100,1) if tot[i] else 0} for i in IND},"사례":[int(r["번호"]) for r in hit[k]]})
gs=collections.OrderedDict()
for m in out["방식"]: gs.setdefault(m["묶음"],set()).update(int(r["번호"]) for r in hit[m["키"]] if r["실제/응용"]=="실제")
order=sorted(gs,key=lambda g:-len(gs[g]))
out["묶음"]=[{"이름":g,"설명":GROUP_DESC[g],"실제":len(gs[g]),"비중":round(len(gs[g])/len(real)*100,1)} for g in order]
out["방식"].sort(key=lambda m:(order.index(m["묶음"]),-m["실제"]))
json.dump(out,open(f"{B}/spec/행사방식.json","w",encoding="utf-8"),ensure_ascii=False,indent=1)
print("실제",len(real),"어느 방식에도 안 듦",none)
